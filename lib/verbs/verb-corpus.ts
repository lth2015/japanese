type TokenPart = readonly [text: string, kana?: string]

type PassiveVerbSeed = {
  id: string
  dictionaryForm: string
  verbGroup: VerbGroup
  meaningZh: string
  conjugatedForm: string
  explanationZh: string
  patternHint: string
  parts: TokenPart[]
  chinese: string
  scene: Scene
  register: Register
}

function makePassiveVerbEntries(seeds: PassiveVerbSeed[]): VerbEntry[] {
  return seeds.map(
    ({
      id,
      dictionaryForm,
      verbGroup,
      meaningZh,
      conjugatedForm,
      explanationZh,
      patternHint,
      parts,
      chinese,
      scene,
      register,
    }) => ({
      id,
      dictionaryForm,
      verbGroup,
      meaningZh,
      conjugations: [
        {
          conjugationType: "passive",
          conjugatedForm,
          explanationZh,
          patternHint,
          examples: [
            {
              japanese: parts.map(([text]) => text).join(""),
              tokens: parts.map(([text, kana]) => (kana ? { text, kana } : { text })),
              kana: parts.map(([text, kana]) => kana ?? text).join(""),
              chinese,
              scene,
              register,
            },
          ],
        },
      ],
    }),
  )
}


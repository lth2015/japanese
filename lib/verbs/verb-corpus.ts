function withCoreConjugations(entries: VerbEntry[]): VerbEntry[] {
  return entries.map((entry) => {
    const existingTypes = new Set<ConjugationType>(
      entry.conjugations.map((conj) => conj.conjugationType),
    )
    const additions = CORE_CONJUGATION_TYPES.filter((type) => !existingTypes.has(type)).map(
      (type) => makeCoreConjugation(entry, type),
    )
    if (additions.length === 0) return entry
    return { ...entry, conjugations: [...entry.conjugations, ...additions] }
  })
}

function makeCoreConjugation(entry: VerbEntry, type: CoreConjugationType): VerbConjugation {
  const form = conjugateCore(entry, type)
  const defaults = FORM_EXAMPLE_TEXT[type]
  const override = CORE_EXAMPLE_OVERRIDES[entry.id]?.[type]
  const lead = override?.lead ?? defaults.lead
  const chinese = override?.chinese ?? `${defaults.chineseLead}${entry.meaningZh}。`
  return {
    conjugationType: type,
    conjugatedForm: form.text,
    explanationZh: getCoreExplanation(type),
    patternHint: getCorePatternHint(entry, type),
    examples: [
      {
        japanese: `${lead}${form.text}。`,
        tokens: [{ text: lead }, { text: form.text, kana: form.kana }, { text: "。" }],
        kana: `${lead}${form.kana}。`,
        chinese,
        scene: override?.scene ?? defaults.scene,
        register: override?.register ?? defaults.register,
      },
    ],
  }
}

function conjugateCore(entry: VerbEntry, type: CoreConjugationType): ConjugatedForm {
  const { dictionaryForm, verbGroup } = entry
  if (dictionaryForm === "来る") {
    switch (type) {
      case "polite":
        return { text: "来ます", kana: "きます" }
      case "potential":
        return { text: "来られる", kana: "こられる" }
      case "negative":
        return { text: "来ない", kana: "こない" }
    }
  }
  if (dictionaryForm === "する") {
    switch (type) {
      case "polite":
        return { text: "します", kana: "します" }
      case "potential":
        return { text: "できる", kana: "できる" }
      case "negative":
        return { text: "しない", kana: "しない" }
    }
  }

  const readingMap = buildReadingMap(entry)
  if (verbGroup === "group3" && dictionaryForm.endsWith("する")) {
    const stem = dictionaryForm.slice(0, -2)
    const stemKana = getReadingForText(stem, readingMap)
    switch (type) {
      case "polite":
        return { text: `${stem}します`, kana: `${stemKana}します` }
      case "potential":
        return { text: `${stem}できる`, kana: `${stemKana}できる` }
      case "negative":
        return { text: `${stem}しない`, kana: `${stemKana}しない` }
    }
  }

  const stem = dictionaryForm.slice(0, -1)
  const stemKana = getReadingForText(stem, readingMap)
  if (verbGroup === "group2") {
    switch (type) {
      case "polite":
        return { text: `${stem}ます`, kana: `${stemKana}ます` }
      case "potential":
        return { text: `${stem}られる`, kana: `${stemKana}られる` }
      case "negative":
        return { text: `${stem}ない`, kana: `${stemKana}ない` }
    }
  }

  const ending = dictionaryForm.at(-1)
  const row = ending ? GROUP1_ROW[ending] : undefined
  if (!row) throw new Error(`Unsupported group1 verb ending: ${dictionaryForm}`)
  switch (type) {
    case "polite":
      return { text: `${stem}${row.polite}`, kana: `${stemKana}${row.politeKana}` }
    case "potential":
      return { text: `${stem}${row.potential}`, kana: `${stemKana}${row.potentialKana}` }
    case "negative":
      return { text: `${stem}${row.negative}`, kana: `${stemKana}${row.negativeKana}` }
  }
}

function buildReadingMap(entry: VerbEntry): Map<string, string> {
  const map = new Map<string, string>()
  for (const conjugation of entry.conjugations) {
    for (const example of conjugation.examples) {
      for (const token of example.tokens) {
        if (token.kana) map.set(token.text, token.kana)
      }
    }
  }
  return map
}

function getReadingForText(text: string, readingMap: Map<string, string>): string {
  let output = ""
  let index = 0
  const keys = [...readingMap.keys()].sort((a, b) => b.length - a.length)
  while (index < text.length) {
    const match = keys.find((key) => text.startsWith(key, index))
    if (match) {
      output += readingMap.get(match)
      index += match.length
    } else {
      output += text[index]
      index += 1
    }
  }
  return output
}

function getCoreExplanation(type: CoreConjugationType): string {
  switch (type) {
    case "polite":
      return "ます形；丁寧に述べる形"
    case "potential":
      return "可能形；できることを表す形"
    case "negative":
      return "ない形；しないことを表す形"
  }
}

function getCorePatternHint(entry: VerbEntry, type: CoreConjugationType): string {
  if (entry.dictionaryForm === "来る") {
    switch (type) {
      case "polite":
        return "三类：来る → 来ます（きます）"
      case "potential":
        return "三类：来る → 来られる（こられる）"
      case "negative":
        return "三类：来る → 来ない（こない）"
    }
  }
  if (entry.dictionaryForm === "する") {
    switch (type) {
      case "polite":
        return "三类：する → します"
      case "potential":
        return "三类：する → できる"
      case "negative":
        return "三类：する → しない"
    }
  }
  if (entry.verbGroup === "group3") {
    switch (type) {
      case "polite":
        return "三类：〜する → 〜します"
      case "potential":
        return "三类：〜する → 〜できる"
      case "negative":
        return "三类：〜する → 〜しない"
    }
  }
  if (entry.verbGroup === "group2") {
    switch (type) {
      case "polite":
        return "二类：語幹 + ます"
      case "potential":
        return "二类：語幹 + られる"
      case "negative":
        return "二类：語幹 + ない"
    }
  }
  switch (type) {
    case "polite":
      return "一类：う段 → い段 + ます"
    case "potential":
      return "一类：う段 → え段 + る"
    case "negative":
      return "一类：う段 → あ段 + ない（う → わない）"
  }
}

